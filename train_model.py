"""Phase 2: train and evaluate the AI-NIDS Random Forest baseline.

Run from project root: python train_model.py
Requires artifacts generated by preprocess.py.
"""
from __future__ import annotations

import json
import logging
import time
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)

ROOT = Path(__file__).resolve().parent
PROCESSED = ROOT / "data" / "processed"
MODELS = ROOT / "models"
RANDOM_STATE = 42

logging.basicConfig(level=logging.INFO, format="%(levelname)s | %(message)s")
logger = logging.getLogger("ai_nids.train")


def read_split(filename: str, features: list[str]) -> tuple[np.ndarray, np.ndarray]:
    path = PROCESSED / filename
    if not path.is_file():
        raise FileNotFoundError(f"Missing {path}; run preprocess.py first")

    # Read float32 to reduce memory use on the ~2.5-million-row dataset.
    dtypes = {column: np.float32 for column in features}
    dtypes["Label"] = np.int8
    frame = pd.read_csv(path, dtype=dtypes)
    expected = features + ["Label"]
    if frame.columns.tolist() != expected:
        raise ValueError(f"Column names/order in {filename} do not match feature_columns.pkl")
    if frame.empty or not frame["Label"].isin([0, 1]).all():
        raise ValueError(f"Invalid or empty labels in {filename}")
    x = frame[features].to_numpy(dtype=np.float32, copy=False)
    if not np.isfinite(x).all():
        raise ValueError(f"Non-finite feature values found in {filename}")
    y = frame["Label"].to_numpy(dtype=np.int8, copy=True)
    return x, y


def main() -> None:
    MODELS.mkdir(parents=True, exist_ok=True)
    features_path = MODELS / "feature_columns.pkl"
    if not features_path.is_file():
        raise FileNotFoundError("Missing models/feature_columns.pkl; run preprocess.py first")
    features = joblib.load(features_path)  # Only load artifacts you created locally.
    if not isinstance(features, list) or not features or len(features) != len(set(features)):
        raise ValueError("Invalid feature metadata")

    logger.info("Loading training split...")
    x_train, y_train = read_split("train.csv", features)
    logger.info("Training: %s flows, %s features", f"{len(y_train):,}", len(features))
    logger.info("Loading testing split...")
    x_test, y_test = read_split("test.csv", features)
    logger.info("Testing: %s flows", f"{len(y_test):,}")

    model = RandomForestClassifier(
        n_estimators=80,
        max_depth=16,
        min_samples_leaf=2,
        max_features="sqrt",
        class_weight="balanced",
        n_jobs=4,
        random_state=42,
    )
    logger.info("Training Random Forest (80 trees, max_depth=16, n_jobs=4)...")
    start = time.perf_counter()
    model.fit(x_train, y_train)
    seconds = time.perf_counter() - start
    logger.info("Training finished in %.1f seconds", seconds)

    logger.info("Evaluating on the held-out test split...")
    predicted = model.predict(x_test)
    cm = confusion_matrix(y_test, predicted, labels=[0, 1])
    scores = {
        "accuracy": float(accuracy_score(y_test, predicted)),
        "precision_malicious": float(precision_score(y_test, predicted, pos_label=1, zero_division=0)),
        "recall_malicious": float(recall_score(y_test, predicted, pos_label=1, zero_division=0)),
        "f1_malicious": float(f1_score(y_test, predicted, pos_label=1, zero_division=0)),
        "confusion_matrix_labels": [0, 1],
        "confusion_matrix": cm.tolist(),
        "training_seconds": round(seconds, 2),
        "train_rows": int(len(y_train)),
        "test_rows": int(len(y_test)),
        "feature_count": len(features),
        "model_parameters": model.get_params(),
        "evaluation_note": "Random stratified flow split; correlated sessions may inflate test scores.",
    }
    print("\n=== TEST METRICS (MALICIOUS = 1) ===")
    for key in ("accuracy", "precision_malicious", "recall_malicious", "f1_malicious"):
        print(f"{key}: {scores[key]:.6f}")
    print("\n=== CONFUSION MATRIX [[TN, FP], [FN, TP]] ===")
    print(cm)
    print("\n=== CLASSIFICATION REPORT ===")
    print(classification_report(y_test, predicted, labels=[0, 1], target_names=["BENIGN", "MALICIOUS"], zero_division=0))

    importance = pd.DataFrame({
        "feature": features,
        "importance": model.feature_importances_,
    }).sort_values("importance", ascending=False)
    print("\n=== TOP 10 GLOBAL FEATURE IMPORTANCES ===")
    print(importance.head(10).to_string(index=False))

    model_path = MODELS / "rf_model.pkl"
    joblib.dump(model, model_path, compress=3)
    importance.to_csv(MODELS / "feature_importances.csv", index=False)
    (MODELS / "evaluation_metrics.json").write_text(
        json.dumps(scores, indent=2), encoding="utf-8"
    )
    logger.info("Saved %s", model_path)
    logger.info("Saved models/feature_importances.csv and models/evaluation_metrics.json")
    logger.info("Phase 2 training complete")


if __name__ == "__main__":
    main()
